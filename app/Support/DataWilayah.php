     * unik secara nasional. Tanpa keterangan itu petugas tidak dapat membedakan
     * Kabupaten Kupang dari Kota Kupang, dan pilihan yang keliru tidak akan
     * pernah memerahkan apa pun.
     *
     * Diurutkan menurut nama agar penelusuran manual tetap mungkin ketika
     * petugas tidak ingat ejaan persisnya.
     *
     * @return array<int, array{id: int, nama: string, provinsi: string}>
     */
    public static function opsiKabupaten(): array
    {
        $provinsi = self::petaProvinsi();

        $opsi = array_map(fn (array $k) => [
            'id' => $k['id'],
            'nama' => $k['nama'],
            'provinsi' => $provinsi[$k['provinsi_id']] ?? '',
        ], self::kabupaten());

        usort($opsi, fn ($a, $b) => strcmp($a['nama'], $b['nama']));

        return $opsi;
    }
}
