    /**
     * Peta id kabupaten ke namanya, untuk pencarian cepat.
     *
     * @return array<int, string>
     */
    public static function petaKabupaten(): array
    {
        return array_column(self::kabupaten(), 'nama', 'id');
    }

    /**
     * Peta id provinsi ke namanya.
     *
     * @return array<int, string>
     */
    public static function petaProvinsi(): array
    {
        return array_column(self::provinsi(), 'nama', 'id');
    }

    /**
     * Nama satu kabupaten, atau null bila idnya tidak dikenal.
     *
     * Mengembalikan null, bukan tanda hubung maupun string kosong: pemanggilnya
     * yang menentukan cara menampilkan nilai yang belum terisi, dan pembeda
     * antara belum diisi dan tidak ditemukan tetap terbaca di sini.
     *
     * @param  int|null  $id  Nilai id kabupaten
     */
    public static function namaKabupaten(?int $id): ?string
    {
        return $id === null ? null : (self::petaKabupaten()[$id] ?? null);
    }

